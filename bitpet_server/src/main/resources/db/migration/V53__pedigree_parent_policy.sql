-- V53: 가계도 부모 등록 정책
--
--   부모는 항상 실존 개체(pet_mst) 참조이며, 소유자와 무관하게 등록할 수 있다.
--   승인·차단 절차는 두지 않는다(검증 도메인 없음) — 사칭 억제는 응답에 소유자를
--   실어 보내 "누구 개체인지 보이게" 하는 것으로 대신한다.
--
--   여기서 스키마가 바뀌는 건 pet_mst.user_id 하나다:
--   탈퇴 익명화 개체를 표현하려면 소유자 없는 개체(user_id IS NULL)가 성립해야 한다.
--   가계도에 남의 개체가 부모로 박혀 있는 이상, 그 주인이 탈퇴했다고 개체를 지울 수는
--   없다 (자식 쪽 가계도가 끊긴다). 소유자만 떼어내고 개체는 남긴다.
--
--   권한 판정은 여전히 pet_keeper_rls 가 단일 소스다. user_id 는 비정규화된 표시용.
-- =============================================================================

ALTER TABLE pet_mst ALTER COLUMN user_id DROP NOT NULL;

COMMENT ON COLUMN pet_mst.user_id IS
    '소유자(표시용 비정규화). NULL = 탈퇴 익명화 개체 — 가계도에서 "정보 없음"으로 노출. 권한 판정은 pet_keeper_rls';
